#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Consolidated plugin ABI + capability table -> work/native/plugin_abi.json"""
import os, json

ROOT = r"data/native"
PLUGINS = ["appcontroller", "etshelper", "filehelper", "httphelper", "sevenzip",
           "shellhelper", "soundhelper", "sqlitepln", "window_control"]

out = {"_note": "generated by work/native/_tools/plugin_abi.py; static PE inspection only",
       "abi": {
           "exports": ["PlnInitiliaze", "PlnOnProcessMessage", "PlnSetParam", "PlnUnInitialize"],
           "note": "PlnInitiliaze spelling has an extra 'i' (observed in every .pln export table)",
           "load": "ETSShell StiCorePlnManager: LoadLibrary + GetProcAddress(PlnInitiliaze/PlnSetParam/PlnOnProcessMessage)",
           "setparam_keys": ["LOG", "WLOG", "EXEC_CALLBACK"],
       },
       "plugins": {}}

for name in PLUGINS:
    mp = os.path.join(ROOT, name, "meta.json")
    if not os.path.exists(mp):
        continue
    m = json.load(open(mp, encoding="utf-8"))
    dp = os.path.join(ROOT, name, "dispatch.json")
    disp = json.load(open(dp, encoding="utf-8")) if os.path.exists(dp) else {}
    p = disp.get("plnonprocess") or {}
    logs = set()
    for f in disp.get("functions", []):
        for l in f.get("log_handlers", []):
            logs.add("%s::%s" % (l["class"], l["method"]))
    data = {
        "file": m["file"],
        "size": m["size"],
        "sha256": m["sha256"],
        "timestamp_utc": m["timestamp_utc"],
        "linker": m["linker"],
        "pdb": next((d.get("pdb") for d in m.get("debug", []) if d.get("type") == 2), None),
        "exports": [{"ordinal": e["ordinal"], "name": e["name"], "rva": e["rva"]}
                    for e in m["exports"]],
        "imports": [{"dll": i["dll"], "count": len(i["functions"])} for i in m["imports"]],
        "rtti_interesting": sorted({r["demangled"] or r["mangled"]
                                    for r in m.get("rtti_classes", [])
                                    if any(k in (r["demangled"] or r["mangled"])
                                           for k in ("Sti", "Stic", "Asiafly", "CppSQLite",
                                                     "DuiLib", "Sound", "Zip", "Json"))}),
        "actions": p.get("action_candidates", []),
        "dispatcher": {"rva": p.get("rva"), "insn_count": p.get("insn_count")},
        "log_handlers": sorted(logs),
        "callback_params": sorted({s for s in (m.get("version_info") or {})} |
                                  {s for s in []}),
        "artifacts": ["work/native/%s/exports.json" % name,
                      "work/native/%s/imports.json" % name,
                      "work/native/%s/strings.txt" % name,
                      "work/native/%s/dispatch.json" % name],
    }
    out["plugins"][name] = data

json.dump(out, open(os.path.join(ROOT, "plugin_abi.json"), "w", encoding="utf-8"),
          ensure_ascii=False, indent=1)
print("wrote plugin_abi.json; plugins:", len(out["plugins"]))
